export type Person = {
  id: string;
  kind: "Member" | "Care Recipient";
  memberId: string | null;
  name: string;
  alias: string;
  dob: string | null;
  centre: string;
  gender: string;
  race: string;
  workingStatus: string;
  preferredLanguage: string;
  onboardingDate: string | null;
  status: string;
  mobility: string;
  hearing: string;
  eyesight: string;
  dietaryPreference: string;
  foodAllergies: string;
  education: string;
  primaryCondition: string;
  tags: string;
  remarks: string;
  createdAt: string;
  updatedAt: string;
  rawImport: Record<string, string | number> | null;
  languages: { language: { name: string }; mode: string }[];
  interests: { interest: { name: string } }[];
  conditions: { condition: { name: string } }[];
  assessments: {
    id: string;
    type: string;
    value: number;
    assessedAt: string | null;
    recordedAt: string;
  }[];
  caregiverLinks: Relationship[];
  recipientLinks: Relationship[];
  participations: {
    id: string;
    programmeId: string;
    status: string;
    programme: { name: string };
  }[];
};
export type Relationship = {
  id: string;
  memberId: string;
  recipientId: string;
  relationship: string;
};
