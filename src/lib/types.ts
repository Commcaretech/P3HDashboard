export type Staff = {
  id: string;
  name: string;
  username: string;
  role: string;
  active: boolean;
};
export type Audit = {
  id: string;
  user: { name: string };
  action: string;
  entityType: string;
  entityId: string;
  timestamp: string;
  changes: { before: unknown; after: unknown };
};
export type Data = {
  people: Person[];
  programmes: Programme[];
  grants: Grant[];
  alerts: Alert[];
  schemes: { id: string; name: string }[];
  staff: Staff[];
  audit: Audit[];
};
export const label = (p: Pick<Person, "name" | "alias" | "memberId">) =>
  p.name || p.alias || p.memberId || "Unnamed record";
export const day = (s: string | null | undefined) => (s ? s.slice(0, 10) : "—");
